-- The source database the end-to-end run queries, with a read-only login for
-- zeteo. Runs once, when the source container's data directory is created.
CREATE SCHEMA sales;

CREATE TABLE sales.customers (
  id integer PRIMARY KEY,
  name text NOT NULL,
  region text NOT NULL
);

CREATE TABLE sales.orders (
  id integer PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES sales.customers (id),
  status text NOT NULL,
  total numeric(10, 2) NOT NULL
);

